describe("decision per item", function()
    local function setup(upgrades, extra)
        local pawn = extra or {}
        pawn.upgrades = upgrades
        local ns = ReloadAddon({ pawn = pawn })
        Login()
        return ns
    end

    it("an upgrade for the main scale is main", function()
        local ns = setup({ ["item:1"] = { "A" } })
        assert_eq(ns.Classify("item:1"), "main")
    end)

    it("an upgrade only for another visible scale is other", function()
        local ns = setup({ ["item:2"] = { "B" } })
        assert_eq(ns.Classify("item:2"), "other")
    end)

    it("an upgrade for both is main", function()
        local ns = setup({ ["item:3"] = { "B", "A" } })
        assert_eq(ns.Classify("item:3"), "main")
    end)

    it("an item level upgrade only is other", function()
        local ns = setup({}, { ilvl = { ["item:4"] = true } })
        assert_eq(ns.Classify("item:4"), "other")
    end)

    it("no answer from Pawn (missing gear data) is not cached", function()
        local ns = setup({ ["item:5"] = { "A" } }, { unknown = { ["item:5"] = 1 } })
        assert_nil(ns.Classify("item:5"))
        assert_eq(ns.Classify("item:5"), "main", "asked again")
        assert_eq(STUB.calls.upgrade, 2)
    end)

    it("secret values and non-strings are not touched", function()
        local ns = setup({ ["item:1"] = { "A" } })
        STUB.secret = "item:1"
        assert_nil(ns.Classify("item:1"))
        assert_nil(ns.Classify(nil))
        assert_nil(ns.Classify(42))
        assert_eq(STUB.calls.upgrade, 0)
    end)

    it("an error inside Pawn is caught", function()
        local ns = setup({})
        PawnIsItemAnUpgrade = function() error("boom") end
        assert_nil(ns.Classify("item:9"))
    end)
end)

describe("main scale", function()
    it("default: the first visible scale in the order of Pawn's list", function()
        local ns = ReloadAddon({ pawn = { scales = {
            { name = "C", label = "Protection", visible = false },
            { name = "B", label = "Retribution", visible = true },
            { name = "A", label = "Holy", visible = true },
        } } })
        Login()
        local main, saved = ns.ResolveMainScale()
        assert_eq(main.name, "B")
        assert_false(saved)
    end)

    it("the saved scale wins when it is visible", function()
        local ns = ReloadAddon({ saved = { mainScale = "B" } })
        Login()
        local main, saved = ns.ResolveMainScale()
        assert_eq(main.name, "B")
        assert_true(saved)
        assert_eq(Output(), "")
    end)

    it("a saved scale that is hidden falls back to the default with one notice", function()
        local ns = ReloadAddon({ saved = { mainScale = "C" }, pawn = { upgrades = { ["item:1"] = { "A" } } } })
        Login()
        assert_eq(ns.ResolveMainScale().name, "A")
        assert_contains(Output(), "the saved main scale C is not a visible Pawn scale for this character; using Holy.")
        assert_eq(ns.Classify("item:1"), "main")
        ClearOutput()
        ns.Invalidate()
        ns.ResolveMainScale()
        assert_eq(Output(), "", "the notice comes once per saved name")
        assert_eq(PawnArrowColorsCharDB.mainScale, "C", "the saved choice is kept for when the scale comes back")
    end)

    it("a saved scale that no longer exists falls back as well", function()
        local ns = ReloadAddon({ saved = { mainScale = "\"PawnForever\":PALADIN2" } })
        Login()
        assert_eq(ns.ResolveMainScale().name, "A")
        assert_contains(Output(), "\"PawnForever\":PALADIN2")
    end)

    it("without any visible scale every upgrade is other", function()
        local ns = ReloadAddon({ pawn = { scales = { { name = "C", label = "Protection", visible = false } }, ilvl = { ["item:1"] = true } } })
        Login()
        assert_nil(ns.ResolveMainScale())
        assert_eq(ns.Classify("item:1"), "other")
    end)

    it("changing the main scale changes the decision", function()
        local ns = ReloadAddon({ pawn = { upgrades = { ["item:2"] = { "B" } } } })
        Login()
        assert_eq(ns.Classify("item:2"), "other")
        ns.SetMainScale("B")
        assert_eq(PawnArrowColorsCharDB.mainScale, "B")
        assert_eq(ns.Classify("item:2"), "main")
    end)
end)

describe("cache", function()
    it("asks Pawn once per link until something is invalidated", function()
        local ns = ReloadAddon({ pawn = { upgrades = { ["item:1"] = { "A" }, ["item:2"] = { "B" } } } })
        Login()
        local before = STUB.calls.scales -- the scale age reads the list at the login
        for _ = 1, 5 do
            ns.Classify("item:1")
            ns.Classify("item:2")
        end
        assert_eq(STUB.calls.upgrade, 2)
        assert_eq(STUB.calls.scales - before, 1, "the main scale is resolved once")
    end)

    it("PawnResetBags forgets the results", function()
        local ns = ReloadAddon({ pawn = { upgrades = { ["item:1"] = { "A" } } } })
        Login()
        assert_eq(STUB.resets, 1, "the addon lets Pawn rate its bag arrows again once its answers are adjusted")
        ns.Classify("item:1")
        PawnResetBags()
        ns.Classify("item:1")
        assert_eq(STUB.calls.upgrade, 2)
        assert_eq(STUB.resets, 2)
    end)

    it("a gear change leaves the invalidation to Pawn's PawnResetBags when Pawn calls it", function()
        local ns = ReloadAddon({ pawn = { upgrades = { ["item:1"] = { "A" } } } })
        Login()
        ns.Classify("item:1")
        FireEvent("PLAYER_EQUIPMENT_CHANGED", 1, false)
        ns.Classify("item:1")
        assert_eq(STUB.calls.upgrade, 1, "not asked again against the old gear")
        PawnResetBags() -- Pawn after its own check of the equipped items
        ns.Classify("item:1")
        assert_eq(STUB.calls.upgrade, 2)
        RunAllTimers()
        ns.Classify("item:1")
        assert_eq(STUB.calls.upgrade, 2, "the addon's own delayed invalidation is dropped")
    end)

    it("a gear change without PawnResetBags (combat) forgets the results after the delay", function()
        local ns = ReloadAddon({ pawn = { upgrades = { ["item:1"] = { "A" } } } })
        Login()
        ns.Classify("item:1")
        FireEvent("PLAYER_EQUIPMENT_CHANGED", 1, false)
        FireEvent("PLAYER_EQUIPMENT_CHANGED", 2, false)
        assert_eq(#STUB.timers, 1, "one delayed invalidation for several slots")
        assert_eq(STUB.timers[1].delay, ns.EQUIP_DELAY)
        RunAllTimers()
        ns.Classify("item:1")
        assert_eq(STUB.calls.upgrade, 2)
    end)

    it("an item Pawn has no stats for yet (no Link) is not cached and asked again", function()
        local ns = ReloadAddon({ pawn = { upgrades = { ["item:1"] = { "B" } }, nolink = { ["item:1"] = 1 } } })
        Login()
        assert_nil(ns.Classify("item:1"))
        assert_eq(STUB.calls.upgrade, 0, "no upgrade question without item data")
        assert_eq(ns.Classify("item:1"), "other")
    end)

    it("a scale made visible in Pawn (PawnResetBags) is taken into account", function()
        local ns = ReloadAddon({ saved = { mainScale = "C" }, pawn = { upgrades = { ["item:7"] = { "C" } } } })
        Login()
        assert_eq(ns.Classify("item:7"), nil, "Pawn has no upgrade for a hidden scale")
        STUB.pawn.scales[3].visible = true
        PawnResetBags()
        assert_eq(ns.ResolveMainScale().name, "C")
        assert_eq(ns.Classify("item:7"), "main")
    end)

    it("several invalidations in one frame lead to one repaint", function()
        local ns = ReloadAddon({})
        Login()
        local passes = 0
        local refresh = ns.paths.blizzard.Refresh
        ns.paths.blizzard.Refresh = function() passes = passes + 1 refresh() end
        PawnResetBags()
        ns.Invalidate()
        ns.SetMainScale("B")
        RunAllTimers()
        assert_eq(passes, 1)
    end)
end)
