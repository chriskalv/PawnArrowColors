-- Core: decision per item link, main scale, cache, start-up and missing Pawn functions.

describe("load", function()
    it("the TOC targets WoW Forever, needs Pawn and saves per character", function()
        assert_eq(ADDON_TOC["Interface"], "16001")
        assert_eq(ADDON_TOC["Interface-Forever"], "16001")
        assert_eq(ADDON_TOC["Version"], "1.1.0")
        assert_eq(ADDON_TOC["Dependencies"], "Pawn")
        assert_eq(ADDON_TOC["OptionalDeps"], "ElvUI")
        assert_eq(ADDON_TOC["SavedVariablesPerCharacter"], "PawnArrowColorsCharDB")
        assert_eq(ADDON_FILES, { "PawnArrowColors/Core.lua", "PawnArrowColors/Bags.lua", "PawnArrowColors/Age.lua",
            "PawnArrowColors/HitCap.lua", "PawnArrowColors/Upgrade.lua", "PawnArrowColors/Pairs.lua",
            "PawnArrowColors/Options.lua" })
    end)

    it("the version in the code matches the TOC", function()
        local ns = ReloadAddon({})
        assert_eq(ns.version, ADDON_TOC["Version"])
    end)

    it("does no work before PLAYER_LOGIN: no Pawn call, no hook, no timer", function()
        local ns = ReloadAddon({ pawn = { upgrades = { ["item:1"] = { "A" } } } })
        STUB.pawnInitialize()
        FireEvent("ADDON_LOADED", "PawnArrowColors")
        assert_nil(ns.Classify("item:1"), "no answer before the login")
        assert_eq(STUB.calls, { upgrade = 0, itemData = 0, scales = 0, arrow = 0 })
        assert_eq(#STUB.timers, 0)
        assert_eq(ns.GetVisibleScales(), {})
        assert_false(ns.setupDone)
    end)

    it("saved variables get their defaults", function()
        local ns = ReloadAddon({ saved = { enabled = "yes", style = "pink", mainScale = 5 } })
        Login()
        local db = PawnArrowColorsCharDB
        assert_eq({ db.enabled, db.style, db.mainScale, db.scaleAgeLevels }, { true, "texture", nil, 3 })
        assert_eq(type(db.scaleAge), "table")
        assert_true(ns.db == PawnArrowColorsCharDB)
    end)

    it("waits for Pawn when Pawn is not initialized at the login, then starts", function()
        local ns = ReloadAddon({ pawn = { initialized = false } })
        Login({ noTimers = true })
        assert_false(ns.setupDone)
        assert_eq(#STUB.timers, 1, "one retry is scheduled")
        STUB.pawnInitialize()
        RunAllTimers()
        assert_true(ns.setupDone)
        assert_true(ns.paths.blizzard.active)
    end)

    it("gives up quietly with one message when Pawn never finishes", function()
        local ns = ReloadAddon({ pawn = { initialized = false } })
        Login()
        RunAllTimers(40)
        assert_false(ns.setupDone)
        assert_contains(Output(), "Pawn did not finish loading")
    end)
end)

describe("Pawn readiness", function()
    it("Pawn is ready through PawnIsReady at the login: set up at once, no Pawn error", function()
        local ns = ReloadAddon({ pawn = { upgrades = { ["item:1"] = { "B" } } } })
        Login({ noTimers = true })
        assert_true(ns.setupDone)
        assert_true(ns.pawnOK)
        assert_true(STUB.readyCalls >= 1, "the addon asked PawnIsReady")
        assert_true(ns.paths.blizzard.active)
        assert_eq(ns.Classify("item:1"), "other")
        assert_eq(STUB.pawnErrors, 0)
    end)

    it("PawnIsReady true only after some tries: the addon waits and then starts", function()
        local ns = ReloadAddon({ pawn = { readyAfter = 3, upgrades = { ["item:1"] = { "A" } } } })
        Login({ noTimers = true })
        assert_false(ns.setupDone)
        assert_nil(ns.Classify("item:1"), "no answer while Pawn is not ready")
        assert_eq(STUB.calls.upgrade, 0)
        for _ = 1, 3 do
            assert_eq(#STUB.timers, 1, "one retry at a time")
            RunTimers()
        end
        assert_true(ns.setupDone)
        assert_eq(ns.Classify("item:1"), "main")
        assert_eq(STUB.pawnErrors, 0, "no Pawn function was called before Pawn was ready")
        assert_eq(Output(), "", "no message when Pawn becomes ready in time")
    end)

    it("without PawnIsReady the addon turns itself off with a clear message and no Lua error", function()
        local ns = ReloadAddon({ pawn = { missing = { PawnIsReady = true }, upgrades = { ["item:1"] = { "B" } } } })
        Login()
        assert_false(ns.setupDone)
        assert_false(ns.pawnOK)
        assert_eq(#STUB.timers, 0, "no retry loop")
        assert_contains(Output(), "PawnIsReady was not found")
        assert_nil(ns.Classify("item:1"))
        assert_eq(STUB.calls, { upgrade = 0, itemData = 0, scales = 0, arrow = 0 })
        assert_eq(STUB.pawnErrors, 0)
    end)

    it("after giving up, /pac refresh sets the addon up once Pawn is ready", function()
        local ns = ReloadAddon({ pawn = { initialized = false, upgrades = { ["item:1"] = { "B" } } } })
        Login()
        RunAllTimers(40)
        assert_false(ns.setupDone)
        assert_contains(Output(), "Pawn did not finish loading")
        STUB.pawnInitialize()
        ClearOutput()
        SlashCmdList.PAWNARROWCOLORS("refresh")
        assert_true(ns.setupDone)
        assert_true(ns.pawnOK)
        assert_not_contains(Output(), "not available")
        assert_eq(ns.Classify("item:1"), "other")
    end)

    it("after giving up, /pac without arguments tries again and shows the state", function()
        local ns = ReloadAddon({ pawn = { initialized = false } })
        Login()
        RunAllTimers(40)
        assert_false(ns.setupDone)
        STUB.pawnInitialize()
        ClearOutput()
        SlashCmdList.PAWNARROWCOLORS("")
        assert_true(ns.setupDone)
        assert_contains(Output(), "main scale: Holy")
        assert_not_contains(Output(), "not available")
    end)

    it("after giving up, /pac refresh while Pawn is still not ready says so and tries again", function()
        local ns = ReloadAddon({ pawn = { initialized = false } })
        Login()
        RunAllTimers(40)
        ClearOutput()
        SlashCmdList.PAWNARROWCOLORS("refresh")
        assert_false(ns.setupDone)
        assert_contains(Output(), "Pawn has not finished loading")
        assert_eq(#STUB.timers, 1, "a new round of retries")
        STUB.pawnInitialize()
        RunAllTimers()
        assert_true(ns.setupDone)
    end)

    it("a second round of tries that gives up again says so again", function()
        local ns = ReloadAddon({ pawn = { initialized = false } })
        Login()
        RunAllTimers(40)
        assert_contains(Output(), "Pawn did not finish loading")
        SlashCmdList.PAWNARROWCOLORS("refresh")
        ClearOutput()
        RunAllTimers(40)
        assert_false(ns.setupDone)
        assert_contains(Output(), "Pawn did not finish loading; the arrows keep Pawn's colors. /pac refresh tries again.")
    end)

    it("/pac while a round of tries is running does not make that round longer", function()
        local ns = ReloadAddon({ pawn = { initialized = false } })
        Login({ noTimers = true })
        local rounds = 0
        for _ = 1, 5 do rounds = rounds + RunTimers() end
        SlashCmdList.PAWNARROWCOLORS("")
        SlashCmdList.PAWNARROWCOLORS("refresh")
        assert_eq(#STUB.timers, 1, "still one retry at a time")
        for _ = 1, 40 do
            if #STUB.timers == 0 then break end
            rounds = rounds + RunTimers()
        end
        assert_false(ns.setupDone)
        assert_true(rounds <= ns.SETUP_TRIES, "at most SETUP_TRIES retries after the login, got " .. rounds)
        assert_contains(Output(), "Pawn did not finish loading")
    end)

    it("a global PawnIsInitialized has no influence (Pawn keeps that flag local)", function()
        -- true as a global while Pawn is not ready: the addon still waits
        local ns = ReloadAddon({ pawn = { initialized = false } })
        PawnIsInitialized = true
        Login()
        RunAllTimers(40)
        assert_false(ns.setupDone)
        assert_eq(STUB.pawnErrors, 0)
        -- no global at all while Pawn is ready (the real client): the addon starts
        ns = ReloadAddon({ pawn = { upgrades = { ["item:1"] = { "B" } } } })
        PawnIsInitialized = nil
        Login()
        assert_true(ns.setupDone)
        assert_eq(ns.Classify("item:1"), "other")
        -- false as a global while Pawn is ready: the addon starts as well
        ns = ReloadAddon({ pawn = {} })
        PawnIsInitialized = false
        Login()
        assert_true(ns.setupDone)
    end)
end)

describe("missing Pawn functions", function()
    it("a missing PawnIsItemAnUpgrade turns the addon off with one message and no Lua error", function()
        local ns = ReloadAddon({ pawn = { missing = { PawnIsItemAnUpgrade = true }, upgrades = { ["item:1"] = { "B" } } } })
